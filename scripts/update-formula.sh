#!/usr/bin/env bash
# Write the Homebrew formula for a release to stdout.
#
#   scripts/update-formula.sh <version> <checksums.txt>  > Formula/hme.rb
#
# <version> is the release version without the leading "v". <checksums.txt>
# is the file GoReleaser publishes with the release: "sha256  filename" lines.
# The release workflow runs this and commits the result, so the formula
# always points at binaries whose checksums were computed in that same run.

set -euo pipefail

[[ $# -eq 2 ]] || {
  echo "usage: $0 <version> <checksums.txt>" >&2
  exit 2
}

version="${1#v}"
checksums="$2"
repo="dewab74/hide-my-email"

[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+([-.][0-9A-Za-z.]+)?$ ]] || {
  echo "error: '$version' is not a version number" >&2
  exit 1
}
[[ -r $checksums ]] || {
  echo "error: cannot read $checksums" >&2
  exit 1
}

# sha_for <os> <arch>: the checksum of that platform's archive.
sha_for() {
  local file="hme_${version}_$1_$2.tar.gz" sha
  sha="$(awk -v f="$file" '$2 == f { print $1 }' "$checksums")"
  [[ $sha =~ ^[0-9a-f]{64}$ ]] || {
    echo "error: no sha256 for $file in $checksums" >&2
    exit 1
  }
  printf '%s' "$sha"
}

# Resolve all four first: a failure inside the heredoc below would not stop
# the script, and a formula with a hole in it must never be published.
darwin_arm64="$(sha_for darwin arm64)"
darwin_amd64="$(sha_for darwin amd64)"
linux_arm64="$(sha_for linux arm64)"
linux_amd64="$(sha_for linux amd64)"

base="https://github.com/${repo}/releases/download/v${version}/hme_${version}"

cat <<EOF_FORMULA
# Generated by scripts/update-formula.sh on each release. Do not edit by hand.
class Hme < Formula
  desc "Manage iCloud Hide My Email addresses from the command-line"
  homepage "https://github.com/${repo}"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "${base}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}_linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}_linux_amd64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "hme"
    man1.install Dir["man/*.1"]
    generate_completions_from_executable(bin/"hme", "completion")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/hme version")
    # With an empty config directory there is no session: exit status 3.
    ENV["HME_CONFIG_DIR"] = testpath.to_s
    ENV["HME_NO_KEYRING"] = "1"
    assert_match "not signed in", shell_output("#{bin}/hme status --offline 2>&1", 3)
    assert_path_exists man1/"hme.1"
  end
end
EOF_FORMULA
